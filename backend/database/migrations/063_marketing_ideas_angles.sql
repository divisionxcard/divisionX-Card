-- 063 · เก็บ "มุมเล่า" หลายมุมต่อ 1 ไอเดีย
--
-- ทำไมต้องมี:
--   ตอนนี้ idea_collector.angle_for() คืนข้อความจาก template ตายตัวแค่ 7 แบบ
--   วัดจากข้อมูลจริง: ไอเดียสถานะ new 86 ชิ้น แต่มุมต่างกันจริงแค่ 24 แบบ
--   หนักสุดคือ 22 ชิ้นใช้ประโยคเดียวกันเป๊ะ ("คอนเทนต์เจาะสาขานี้ — โพสต์บอกทำเล...")
--
--   นี่คือ "รากจริง" ของปัญหาคอนเทนต์ซ้ำที่เจ้าของบ่นมาตลอด — เคยแก้ที่ปลายทางแล้ว
--   (สุ่มรูปแบบการเขียน 8 แบบ + ให้ AI เห็นแคปชั่นเก่า) แต่ต้นทางยังป้อนโจทย์เดิมซ้ำ ๆ
--   ป้อนโจทย์เดียวกัน 22 ครั้ง ต่อให้เขียนดีแค่ไหนก็ออกมาแนวเดียวกัน
--
-- แก้ยังไง:
--   ให้ AI คิดมุมเล่า 3 มุมที่ "ต่างกันจริง" จากข่าวแต่ละชิ้น แล้วเก็บเป็น array
--   คนเลือกเองว่าจะเอามุมไหนไปเขียน (แบบเดียวกับที่ Hero AI ทำ)
--
-- รูปแบบข้อมูล: [{"label":"ชื่อมุมสั้น ๆ","brief":"อธิบายว่าจะเล่ายังไง"}]
--   label เอาไว้โชว์เป็นชิปให้กด · brief เอาไปใส่ prompt ตอนเขียนแคปชั่น
--
-- ปลอดภัยกับของเดิม: เป็น nullable ไม่มี default · คอลัมน์ angle เดิมยังอยู่
--   ใช้เป็นทางถอยเมื่อ angles ว่าง (ไอเดียเก่าที่เก็บมาก่อนหน้านี้ไม่มี angles)

ALTER TABLE marketing_ideas
  ADD COLUMN IF NOT EXISTS angles jsonb;

COMMENT ON COLUMN marketing_ideas.angles IS
  'มุมเล่าหลายมุมที่ AI คิดจากข่าวชิ้นนี้ [{label,brief}] · ว่าง = ใช้คอลัมน์ angle เดิมแทน';

-- เก็บว่ามุมไหนถูกเลือกไปเขียนจริง — ภายหลังดูได้ว่ามุมแบบไหนคนหยิบบ่อย/ได้ผลดี
ALTER TABLE marketing_ideas
  ADD COLUMN IF NOT EXISTS chosen_angle text;

COMMENT ON COLUMN marketing_ideas.chosen_angle IS
  'label ของมุมที่ถูกเลือกไปสร้างคอนเทนต์ · null = ยังไม่ได้เลือก';

-- ใช้หาไอเดียที่ยังไม่มีมุมให้เลือก (ตัวเติมมุมย้อนหลังจะวิ่งหาแถวพวกนี้)
CREATE INDEX IF NOT EXISTS idx_marketing_ideas_no_angles
  ON marketing_ideas (status)
  WHERE angles IS NULL;
