ALTER TABLE machine_stock
  ADD COLUMN IF NOT EXISTS empty_since TIMESTAMPTZ;

COMMENT ON COLUMN machine_stock.empty_since IS
  'ช่องนี้ของหมด (remain=0) ต่อเนื่องมาตั้งแต่เมื่อไหร่ · มีของแล้วจะถูกล้างเป็น NULL · '
  'ใช้ติดธง "ว่างค้างแต่เติมไม่ได้" บนใบจัดของ · NULL = มีของ หรือยังไม่ได้ sync รอบใหม่';

-- ใช้หาช่องที่ว่างค้างนาน ๆ (ใบจัดของ + สรุปเข้า Telegram)
CREATE INDEX IF NOT EXISTS idx_machine_stock_empty_since
  ON machine_stock (empty_since)
  WHERE empty_since IS NOT NULL;

-- ═══ Verify ═══
SELECT machine_id, slot_number, product_name, remain, empty_since
FROM machine_stock
WHERE empty_since IS NOT NULL
ORDER BY empty_since
LIMIT 20;
