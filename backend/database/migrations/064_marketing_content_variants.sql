-- 064 · เก็บคอนเทนต์หลายช่องทางจากไอเดียเดียว
--
-- ทำไมต้องมี:
--   ตอนนี้ 1 แถว = 1 ช่องทาง (คอลัมน์ platform) ถ้าอยากลง FB + IG + TikTok
--   ต้องกดสร้างใหม่ 3 รอบ แล้วก็ได้แคปชั่นเดียวกันเป๊ะเพราะโจทย์เดียวกัน
--   ซึ่งผิด — แต่ละช่องทางมีธรรมเนียมคนละแบบ (TikTok สั้นมาก · FB ยาวได้ · IG ภาพนำ)
--
--   แนวคิดนี้ได้จาก heroaiengine ที่เจ้าของเอามาให้ดู — เขาสร้างครั้งเดียวได้
--   FB/IG/TikTok/สคริปต์วิดีโอ พร้อมกัน แล้วปรับแยกกันได้
--
-- ทำไมเก็บเป็น jsonb ในแถวเดิม ไม่แยกเป็นหลายแถว:
--   วงจรอนุมัติของเราคือ "1 การ์ด = 1 เรื่อง" ถ้าแยกแถวจะกลายเป็น 4 การ์ดที่ต้อง
--   อนุมัติซ้ำ 4 รอบทั้งที่เป็นเรื่องเดียวกัน · เก็บรวมแล้วโชว์เป็นแท็บในการ์ดเดียว
--   ตรงกับวิธีทำงานจริงมากกว่า (ก๊อปทีละช่องไปวางในแต่ละแอป)
--
-- รูปแบบ: {"ig": "...", "tiktok": "...", "script": "..."}
--   caption เดิมยังเป็นตัวหลัก (Facebook) — ไม่ย้าย ไม่ทำลายของเก่า

ALTER TABLE marketing_content
  ADD COLUMN IF NOT EXISTS variants jsonb;

COMMENT ON COLUMN marketing_content.variants IS
  'แคปชั่นสำหรับช่องทางอื่นจากเรื่องเดียวกัน {ig,tiktok,script} · caption = ตัวหลัก (Facebook)';
