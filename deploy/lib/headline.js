//
// ⚠️ ทำไมต้องมี (27 ส.ค. 2026):
//   เดิมส่งบรรทัดแรกของแคปชั่นทั้งดุ้นไปเป็น "Headline text to place"
//   วัดจากคิวจริง 20 ชิ้น: เฉลี่ย 77 ตัวอักษร ยาวสุด 108
//   ยัดลงกรอบ 1024x1024 แล้วตัวหนังสือต้องเล็กจนอ่านยาก และผิดกฎแบรนด์ตัวเอง
//   ที่เขียนว่าพาดหัวไม่เกิน 2 บรรทัด กับตัวอักษรหลักต้องใหญ่พอ
//
// ⚠️ และยิ่งข้อความยาว ความเสี่ยงที่โมเดลสะกดไทยเพี้ยนยิ่งสูง
//   ซึ่งเป็นข้อได้เปรียบเดียวที่ทำให้เลิกใช้เทมเพลตได้ — ไม่ควรเอาไปทิ้ง
//
// ⚠️ ภาษาไทยไม่เว้นวรรคระหว่างคำ แต่เว้นวรรคที่ขอบวลี
//   → "ไทย เว้นวรรค ไทย" คือจุดตัดที่ปลอดภัย
//   → "One Piece" มีอังกฤษประกบสองข้าง จึงไม่มีวันถูกตัดกลาง
//   (บทเรียนเดียวกับ deploy/agents/poster_render.py → split_head)

export const HEAD_MAX = 30
export const SUB_MAX = 62

// ยอมยาวเกินเพดานได้ถึงตรงนี้ ถ้าการตัดตรงเพดานจะทำให้คำขาดกลาง
export const HEAD_HARD = 46
// บรรทัดรอง: ทั้งประโยคยาวไม่เกินนี้ = ใช้ทั้งประโยค ไม่ตัด (24 ต.ค. 2026)
//   #69 "🎮 ในโลกโปเกมอนยุค Gen 5 มีของอยู่ 3 ชิ้นที่ฟังแล้วต้องขยี้ตาอีกรอบ" ยาว 66 > SUB_MAX
//   ถูกตัดเหลือ "…มีของอยู่ 3" ขึ้นโปสเตอร์ — ประโยคครบยาวกว่านิดหน่อยอ่านง่ายกว่าเศษประโยคเสมอ
export const SUB_HARD = 80

// สระบน/ล่าง วรรณยุกต์ และตัวการันต์ — พวกนี้เกาะตัวพยัญชนะข้างหน้า
// ตัดตรงหน้าตัวพวกนี้เมื่อไหร่ คำจะขาดครึ่งทันที ("อื่น" → "อื" + "่น")
const COMBINING = /[ัิ-ฺ็-๎]/

// สระหน้า เ แ โ ใ ไ — เขียนไว้ "ก่อน" พยัญชนะที่มันออกเสียงคู่ด้วย
// จบพาดหัวด้วยตัวพวกนี้เมื่อไหร่ คือทิ้งสระเดี่ยวห้อยไว้แล้วคำที่เหลือไปขึ้นบรรทัดรอง
// เจอจริงตอนทดสอบ: "...มากขึ้นเ" + "รื่อยๆ" ซึ่งอ่านไม่ออกทั้งสองฝั่ง
const LEADING_VOWEL = /[เ-ไ]/

// คำเชื่อมที่ถ้าขึ้นต้นวลีใหม่ ตัดตรงนั้นได้ความหมายครบ
//
// ⚠️ ต้องมีช่องว่างนำหน้าเสมอ — ไทยไม่เว้นวรรคระหว่างคำ ถ้าไม่บังคับ
//    "แต่" จะไปเจอตัวที่อยู่ข้างใน "ตั้งแต่" แล้วตัดกลางคำ
const CONJ = ["แต่", "เพราะ", "จนกว่า", "จนถึง", "แล้ว", "ถ้า", "หาก",
              "ซึ่ง", "จึง", "ก่อนที่", "หลังจาก", "พร้อม"]

const SEP = /[—–·:|…]/

// ช่องว่างระหว่าง "เลขล้วน" กับ "หน่วย" ไม่ใช่ขอบวลี — "3 ชิ้น" "20 เท่า" "3.55 ล้าน" คือก้อนเดียวกัน
// ⚠️ เฉพาะเลขล้วนตามด้วยหน่วยเท่านั้น — รหัสชุด "FB-09 Dragonball" / "OP16 ที่…" / "HP 350 พร้อม…" ตัดได้ตามเดิม
//    (รอบแรกห้ามทุกช่องว่างหลังตัวเลข → พาดหัว "ฟิวชั่นดวลมังกร! 🌋 FB-09" เสียรหัสชุด)
const UNIT = /^(ชิ้น|ใบ|ซอง|กล่อง|เท่า|ล้าน|แสน|หมื่น|พัน|ร้อย|บาท|ดอลลาร์|ตัว|คน|วัน|วินาที|นาที|ชั่วโมง|เดือน|ปี|ครั้ง|อันดับ|แบบ|ชุด|อย่าง|ข้อ|รอบ|เปอร์เซ็นต์|%|ตู้|สาขา|ห้าง|แห่ง)/
const okSpace = (t, i) => {
  if (i <= 0) return false
  const left = t.slice(0, i).split(/\s/).pop()
  return !(/^[\d.,]+$/.test(left) && UNIT.test(t.slice(i + 1)))
}

function cut(s, limit, hard = HEAD_HARD) {
  const t = s.trim()
  if (t.length <= limit) return { head: t, rest: "" }

  // 1) ตัวคั่นชัดเจน — ผู้เขียนตั้งใจแบ่งความตรงนั้นอยู่แล้ว
  for (let i = Math.min(limit, t.length - 1); i > limit * 0.4; i--) {
    if (SEP.test(t[i])) {
      return { head: t.slice(0, i).trim(), rest: t.slice(i + 1).trim() }
    }
  }

  // 2) คำเชื่อมที่มีช่องว่างนำหน้า
  let best = -1
  for (const c of CONJ) {
    let from = 0
    for (;;) {
      const at = t.indexOf(" " + c, from)
      if (at < 0 || at > limit) break
      if (at > best && at > limit * 0.35) best = at
      from = at + 1
    }
  }
  if (best > 0) return { head: t.slice(0, best).trim(), rest: t.slice(best).trim() }

  // 3) ช่องว่างธรรมดา — ในภาษาไทยคือขอบวลี (ข้ามช่องว่างหลังตัวเลข)
  let sp = t.lastIndexOf(" ", limit)
  while (sp > 0 && !okSpace(t, sp)) sp = t.lastIndexOf(" ", sp - 1)
  if (sp > limit * 0.35) return { head: t.slice(0, sp).trim(), rest: t.slice(sp).trim() }

  // 4) ไม่มีจุดตัดในเพดาน — ยืดไปหาช่องว่างถัดไปแทนการตัดตรง ๆ
  //
  // ⚠️ ห้ามตัดกลางคำไทยเด็ดขาด พาดหัวยาวเกินไปหน่อยยังอ่านรู้เรื่อง
  //    แต่ "ถึงกับ" ที่ขาดเป็น "ถึงก" + "ับ" อ่านไม่ออกเลย
  //    เจอจริงตอนทดสอบกับคิว 34 ชิ้น: #22 #26 #32 #34 #36 ขาดกลางคำหมด
  let next = t.indexOf(" ", limit)
  while (next > 0 && !okSpace(t, next)) next = t.indexOf(" ", next + 1)
  if (next > 0 && next <= hard) {
    return { head: t.slice(0, next).trim(), rest: t.slice(next).trim() }
  }
  // 4b) ท้ายย่อหน้าก็เป็นจุดตัดที่ปลอดภัย — ทั้งก้อนยาวไม่เกินเพดานแข็ง ใช้ทั้งก้อน
  //     (21 ต.ค. 2026 ตอนเปลี่ยนเป็นตัดเฉพาะย่อหน้าแรก: #36 #47 เคยรอดเพราะช่องว่างที่ต่อย่อหน้าถัดไป)
  if (t.length <= hard) return { head: t, rest: "" }

  // 5) ยาวทั้งดุ้นไม่มีช่องว่างเลย — ถอยจนจุดตัดไม่ผ่ากลางคำ
  //
  // ต้องพ้นทั้งสองแบบ:
  //   - t[i]   เป็นสระบน/ล่างหรือวรรณยุกต์ = มันเกาะตัวที่เพิ่งตัดไป
  //   - t[i-1] เป็นสระหน้า (เ แ โ ใ ไ) = พาดหัวจะจบด้วยสระลอย ๆ
  let i = Math.min(limit, t.length)
  while (i > 1 && (COMBINING.test(t[i] || "") || LEADING_VOWEL.test(t[i - 1]))) i--
  return { head: t.slice(0, i).trim(), rest: t.slice(i).trim() }
}

// จำนวนตู้/สาขา/ห้าง — กฎเหล็กข้อ 5 ห้ามพิมพ์ลงภาพ (ตัวเลขเปลี่ยนทุกสัปดาห์ โปสเตอร์อยู่นานกว่า)
// เลขที่ติดตัวอักษร/ขีดข้างหน้าคือรหัสชุด ไม่ใช่จำนวน ("ซอง OP-14 ตู้ไหนก็มี" ไม่ใช่ "14 ตู้")
const COUNT = /(?<![A-Za-z\d-])\d[\d,]*\s*(?:ตู้|สาขา|ห้าง|แห่ง)/
// ตัวคั่นที่มีช่องว่างล้อม = ผู้เขียนแบ่งท่อนความเอง ("13 ตู้ของ OP-14 … — ถ้าให้เลือก…")
const CLAUSE_SEP = /\s+[—–|·]\s+/

/**
 * ทิ้งท่อนที่มีจำนวนตู้/สาขาก่อนเอาไปทำพาดหัว (ฟังก์ชันล้วน — ทดสอบได้)
 *
 * ⚠️ 21 ต.ค. 2026 — แคปชั่น #63 ขึ้นต้น "13 ตู้ของ OP-14 ชนกับ 12 ตู้ของ OP-16 — ถ้าให้เลือกกดได้แค่ตู้เดียว …"
 *    พาดหัวออกมาเป็น "13 ตู้ของ OP-14 ชนกับ 12" ทั้งตัดกลางวลี และส่งจำนวนตู้ให้โมเดลเขียนลงภาพ
 *    ขัดกับกฎเหล็กข้อ 5 ในบรีฟเดียวกัน (สั่งทั้ง "copy exactly" และ "never print a machine count")
 * ทิ้งเป็นท่อนตามตัวคั่น · ท่อนไหนแยกไม่ได้ก็ทิ้งทั้งบรรทัด · ทิ้งแล้วไม่เหลืออะไร = ใช้ของเดิม
 */
export function dropCountClauses(caption) {
  const lines = String(caption || "").split("\n")
  const kept = []
  for (const line of lines) {
    if (!COUNT.test(line)) { kept.push(line); continue }
    const parts = line.split(CLAUSE_SEP).filter(p => !COUNT.test(p))
    if (parts.length) kept.push(parts.join(" — "))
  }
  const out = kept.join("\n")
  return out.replace(/#\S+/g, "").trim() ? out : String(caption || "")
}

/**
 * @param {string} caption แคปชั่นเต็ม (ยังมีแฮชแท็กได้ ฟังก์ชันนี้ตัดให้เอง)
 * @returns {{headline:string, sub:string}} sub เป็น "" ได้ถ้าไม่มีอะไรเหลือ
 */
export function splitHeadline(caption) {
  caption = dropCountClauses(caption)
  const tidy = (s) => s.replace(/#\S+/g, " ").replace(/\s+/g, " ").trim()
  const paras = String(caption || "").split("\n").map(tidy).filter(Boolean)
  if (!paras.length) return { headline: "", sub: "" }

  // ⚠️ 21 ต.ค. 2026 — ตัดจากย่อหน้าแรกเท่านั้น · เดิมรวมทั้งแคปชั่นเป็นบรรทัดเดียวก่อนตัด
  //    บรรทัดรองจึงลากข้ามไปย่อหน้าถัดไป (#63: "นายเดินเข้าหาตู้ไหนก่อน? บางคนเลือกชุดที่…")
  const first = cut(paras[0], HEAD_MAX)
  // ตัวคั่นห้อยท้ายพาดหัว ("กติกาง่าย ๆ:") ไม่มีความหมายบนโปสเตอร์ — ประโยคถัดไปอยู่บรรทัดรองแล้ว
  const headline = first.head.replace(/\s*[:—–·|]+$/, "")

  // บรรทัดรองมาจากส่วนที่เหลือของประโยคแรก ถ้าไม่มีค่อยไปเอาย่อหน้าถัดไป
  const subSource = first.rest || paras[1] || ""
  // ทั้งประโยคไม่เกิน SUB_HARD = ใช้ทั้งประโยค · ยาวกว่านั้นค่อยตัด (เพดานแข็งของบรรทัดรอง = SUB_HARD)
  const subText = subSource.trim()
  const sub = !subText ? "" : subText.length <= SUB_HARD ? subText : cut(subText, SUB_MAX, SUB_HARD).head

  return { headline, sub }
}

export default { splitHeadline, dropCountClauses, HEAD_MAX, SUB_MAX, SUB_HARD }
