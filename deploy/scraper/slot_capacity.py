PACK_SLOT_MAX = 12


def is_box(product_name):
    """ช่องนี้เป็นสินค้าแบบกล่องไหม — ดูจากชื่อ เหมือนที่หน้าเว็บใช้"""
    return "box" in (product_name or "").lower()


def plan_capacity(reported, product_name=None):
    """ความจุที่เอาไปคิดยอดเติม · ซองไม่เกิน PACK_SLOT_MAX · กล่องใช้ตามที่ตู้รายงาน"""
    cap = int(reported or 0)
    return cap if is_box(product_name) else min(cap, PACK_SLOT_MAX)
