// ── อักษรที่หน้าตาเหมือนไทยแต่ไม่ใช่ไทย ────────────────────────────────
// ยกมาจากโปรเจกต์ต้นทาง (เคสจริง: โมเดลสะกด "เสียง" ด้วยอักษรลาว 2 ตัว
// บล็อกลาว U+0E80-U+0EFF อยู่ติดกับไทย U+0E00-U+0E7F รูปร่างจึงคล้ายจนตาคนอ่านผ่าน)
// สำคัญมากเมื่อข้อความมาจาก LLM และจะถูกเอาไปให้โมเดลวาดภาพเขียนตาม
const CONFUSABLE_SCRIPTS = [
  { name: "ลาว", re: /[຀-໿]/g },
  { name: "เขมร", re: /[ក-៿]/g },
  { name: "พม่า", re: /[က-႟]/g },
]

/** หาอักขระต่างภาษาที่ปนในข้อความไทย — คืน [] ถ้าสะอาด */
export function findForeignChars(text) {
  const s = String(text || "")
  const out = []
  for (const { name, re } of CONFUSABLE_SCRIPTS) {
    re.lastIndex = 0
    let m
    while ((m = re.exec(s)) !== null) {
      out.push({
        script: name,
        ch: m[0],
        code: "U+" + m[0].codePointAt(0).toString(16).toUpperCase().padStart(4, "0"),
        at: m.index,
        context: s.slice(Math.max(0, m.index - 10), m.index + 10).replace(/\s+/g, " "),
      })
    }
  }
  return out.sort((a, b) => a.at - b.at)
}

/**
 * ตรวจข้อความหนึ่งก้อนกับกฎทั้งหมด
 * @param {string} text
 * @param {string} where ป้ายบอกว่าข้อความนี้มาจากไหน (ใช้ในข้อความเตือน)
 * @returns {Array<{id,severity,message,fix,where}>}
 */
export function checkText(text, where = "ข้อความ") {
  const s = String(text || "")
  if (!s.trim()) return []
  const found = []
  for (const rule of PHRASE_RULES) {
    if (rule.test.test(s)) {
      found.push({ id: rule.id, severity: rule.severity, where,
                   message: rule.message, fix: rule.fix })
    }
  }
  const foreign = findForeignChars(s)
  if (foreign.length) {
    const scripts = [...new Set(foreign.map(f => f.script))].join(" · ")
    const sample = foreign.slice(0, 3)
      .map(f => `'${f.ch}' (${f.code}) ที่ "…${f.context}…"`).join("  ·  ")
    found.push({
      id: "confusable_script",
      severity: SEVERITY.BLOCK,
      where,
      message: `พบอักษร${scripts}ปนในข้อความไทย ${foreign.length} ตัว — ${sample}`,
      fix: "พิมพ์คำนั้นใหม่ด้วยแป้นภาษาไทย อักขระพวกนี้มองด้วยตาไม่ออกแต่ผิดถาวรเมื่อโพสต์",
    })
  }
  return found
}

